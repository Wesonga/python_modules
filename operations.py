a = 10
b = 3

result = a + b
print(f"The sum of {a} and {b} is: {result}")

result = a - b
print(f"The difference of {a} and {b} is: {result}")

result = a / b
print(f"The division of {a} by {b} is: {result}")

result = a // b
print(f"The floor division of {a} by {b} is: {result}")

result = a % b
print(f"The modulus of {a} and {b} is: {result}")

result = a ** b
print(f"The exponentiation of {a} to the power of {b} is: {result}")

print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
print(a == b)
print(a != b)

# assignment operators
score = 10
score += 5
score -= 3

print(score)